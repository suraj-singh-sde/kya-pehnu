import { useMutation, useQuery } from "@tanstack/react-query";
import { api, errorMessage, imageUrl, unwrap } from "@/api/client";
import { Button } from "@/components/ui/button";

type Pictures = {
  thumb_path?: string | null;
  alt_thumb_path?: string | null;
  picture_generated?: boolean;
};
type Props = { kind: "item" | "piece"; id: number; row: Pictures; onChange: () => void };
type Action = "make" | "switch" | "delete";

function call(kind: Props["kind"], id: number, action: Action): Promise<unknown> {
  if (kind === "item") {
    const params = { params: { path: { item_id: id } } };
    if (action === "make") return unwrap(api.POST("/api/items/{item_id}/clean-picture", params));
    if (action === "switch") return unwrap(api.POST("/api/items/{item_id}/clean-picture/switch", params));
    return unwrap(api.DELETE("/api/items/{item_id}/clean-picture", params));
  }
  const params = { params: { path: { piece_id: id } } };
  if (action === "make") return unwrap(api.POST("/api/ingest/pieces/{piece_id}/clean-picture", params));
  if (action === "switch") return unwrap(api.POST("/api/ingest/pieces/{piece_id}/clean-picture/switch", params));
  return unwrap(api.DELETE("/api/ingest/pieces/{piece_id}/clean-picture", params));
}

/** A product-style picture of the garment, generated by OpenAI. The original photo crop is always kept. */
export function CleanPicture({ kind, id, row, onChange }: Props) {
  const settings = useQuery({ queryKey: ["settings"], queryFn: () => unwrap(api.GET("/api/settings")) });
  const act = useMutation({ mutationFn: (action: Action) => call(kind, id, action), onSuccess: onChange });
  const available = settings.data?.clean_pictures ?? false;
  const hasBoth = !!row.alt_thumb_path;
  if (!available && !hasBoth) return null;

  const generatedShown = !!row.picture_generated;
  const original = generatedShown ? row.alt_thumb_path : row.thumb_path;
  const clean = generatedShown ? row.thumb_path : row.alt_thumb_path;
  const thumb = (path: string | null | undefined, label: string, shown: boolean) => (
    <figure className="text-center text-xs">
      <img
        src={imageUrl(path)}
        alt={label}
        className={`h-24 w-24 rounded border bg-muted/40 object-contain ${shown ? "ring-2 ring-primary" : ""}`}
      />
      <figcaption>
        {label}
        {shown ? " (shown)" : ""}
      </figcaption>
    </figure>
  );

  return (
    <div className="space-y-2 rounded-md border p-2 text-sm">
      {hasBoth && (
        <div className="flex gap-3">
          {thumb(original, "Original", !generatedShown)}
          {thumb(clean, "Clean picture", generatedShown)}
        </div>
      )}
      <div className="flex flex-wrap gap-2">
        {hasBoth && (
          <Button size="sm" variant="outline" disabled={act.isPending} onClick={() => act.mutate("switch")}>
            {generatedShown ? "Use original" : "Use clean picture"}
          </Button>
        )}
        {available && (
          <Button size="sm" variant="outline" disabled={act.isPending} onClick={() => act.mutate("make")}>
            {act.isPending && act.variables === "make" ? "Making it… (up to a minute)" : hasBoth ? "Make another" : "Make clean picture"}
          </Button>
        )}
        {hasBoth && (
          <Button size="sm" variant="ghost" disabled={act.isPending} onClick={() => act.mutate("delete")}>
            Delete clean picture
          </Button>
        )}
      </div>
      {available && (
        <p className="text-xs text-muted-foreground">
          Uses one paid OpenAI image generation. The result is a redrawing, so check colours and details against the original.
        </p>
      )}
      {act.error && <p className="text-destructive">{errorMessage(act.error)}</p>}
    </div>
  );
}
